/** 按语言选用的问题池（当前仅中文；英文可后续扩展） */
const POOL: Record<Language, { L1: string[]; L2: string[]; L3: string[] }> = {
  zh: { L1: L1_FACT, L2: L2_EMOTION, L3: L3_REFLECTION },
  en: { L1: L1_FACT, L2: L2_EMOTION, L3: L3_REFLECTION },
};

/**
 * 从数组中随机抽取 n 个不重复元素。
 * @param arr - 源数组
 * @param n - 抽取数量，若超过长度则取满
 * @returns 随机选出的字符串数组
 */
function pickRandom(arr: string[], n: number): string[] {
  if (n <= 0) return [];
  const max = Math.min(n, arr.length);
  const indices = new Set<number>();
  while (indices.size < max) {
    indices.add(Math.floor(Math.random() * arr.length));
  }
  return Array.from(indices).map((i) => arr[i]);
}

/**
 * 按 L1 / L2 / L3 规则生成引导问题：L1 随机 2–3 个，L2 随机 1–2 个，L3 固定 1 个。
 * 每次页面初始化（如切换日期、语言）时调用，结果随语言与依赖稳定。
 *
 * @param lang - 页面语言，用于选用对应问题池（当前中英共用同一批中文题干）
 * @returns 按 L1 → L2 → L3 顺序拼接的问题数组，共 4–6 条
 */
export function getRandomPromptGuides(lang: Language): string[] {
  const { L1, L2, L3 } = POOL[lang];
  const fromL1 = pickRandom(L1, 2 + Math.floor(Math.random() * 2)); // 2 或 3
  const fromL2 = pickRandom(L2, 1 + Math.floor(Math.random() * 2)); // 1 或 2
  const fromL3 = pickRandom(L3, 1); // 固定 1
  return [...fromL1, ...fromL2, ...fromL3];
}

/**
 * 从 L1 / L2 / L3 合并池中随机取 1 个问题，不区分层级。
 * 用于当天已有记录时，替换输入框占位语「此刻在想什么」。
 *
 * @param lang - 页面语言
 * @returns 随机一条问题，池为空时返回空字符串
 */
export function getRandomPlaceholderQuestion(lang: Language): string {
  const { L1, L2, L3 } = POOL[lang];
  const all = [...L1, ...L2, ...L3];
  const picked = pickRandom(all, 1);
  return picked[0] ?? '';
}
